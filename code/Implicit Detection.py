from datasets import Dataset

def tokenize_example(example):
    formatted_text = tokenizer.apply_chat_template(
        example["messages"],
        tokenize=False,
        add_generation_prompt=False
    )

    encoded = tokenizer(
        formatted_text,
        truncation=True,
        max_length=MAX_LENGTH,
        padding=False
    )

    # Causal language modeling: predict the complete conversation
    encoded["labels"] = encoded["input_ids"].copy()

    return encoded


def prepare_dataset(data, split_name):
    print(f"\nTokenizing {split_name} dataset...")

    dataset = Dataset.from_pandas(
        data[["messages"]].reset_index(drop=True),
        preserve_index=False
    )

    tokenized = dataset.map(
        tokenize_example,
        remove_columns=dataset.column_names,
        desc=f"Tokenizing {split_name}"
    )

    print(f"{split_name} examples: {len(tokenized)}")
    print("Example token count:", len(tokenized[0]["input_ids"]))

    return tokenized


