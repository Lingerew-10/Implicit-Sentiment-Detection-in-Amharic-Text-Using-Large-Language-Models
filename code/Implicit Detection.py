import pandas as pd
import numpy as np
from statsmodels.stats.inter_rater import fleiss_kappa

# ------------------------------------------------------------
# 1. Select the annotation DataFrame and columns
# ------------------------------------------------------------

annotation_df = train_df.copy()  # Change if annotations are elsewhere

annotator_columns = [
    "annotator_1",
    "annotator_2",
    "annotator_3"
]

# Verify columns
missing = [
    col for col in annotator_columns
    if col not in annotation_df.columns
]

if missing:
    print("Annotation columns not found:", missing)
    print("Available columns:", annotation_df.columns.tolist())

else:
    # --------------------------------------------------------
    # 2. Prepare annotation data
    # --------------------------------------------------------

    labels = annotation_df[annotator_columns].copy()

    labels = labels.replace(r"^\s*$", np.nan, regex=True)
    labels = labels.dropna()

    labels = labels.apply(
        lambda col: col.astype(str).str.strip().str.capitalize()
    )

    print("Valid annotated sentences:", len(labels))
    print("Annotators:", len(annotator_columns))

    # --------------------------------------------------------
    # 3. Calculate unanimous and partial agreement
    # --------------------------------------------------------

    unanimous = (labels.nunique(axis=1) == 1).sum()
    partial = len(labels) - unanimous

    unanimous_percentage = unanimous / len(labels) * 100
    partial_percentage = partial / len(labels) * 100

    print("\nUNANIMOUS AGREEMENT")
    print("All three agree:", unanimous)
    print(f"Percentage: {unanimous_percentage:.2f}%")

    print("\nPARTIAL AGREEMENT")
    print("Not unanimous:", partial)
    print(f"Percentage: {partial_percentage:.2f}%")

    # --------------------------------------------------------
    # 4. Calculate Fleiss' Kappa
    # --------------------------------------------------------

    categories = sorted(labels.stack().unique())

    agreement_matrix = np.array([
        [(row == category).sum() for category in categories]
        for _, row in labels.iterrows()
    ])

    kappa = fleiss_kappa(
        agreement_matrix,
        method="fleiss"
    )

    print("\nFLEISS' KAPPA")
    print(f"Fleiss' Kappa: {kappa:.4f}")

    # --------------------------------------------------------
    # 5. Interpretation
    # --------------------------------------------------------

    if kappa < 0:
        interpretation = "Poor agreement"
    elif kappa <= 0.20:
        interpretation = "Slight agreement"
    elif kappa <= 0.40:
        interpretation = "Fair agreement"
    elif kappa <= 0.60:
        interpretation = "Moderate agreement"
    elif kappa <= 0.80:
        interpretation = "Substantial agreement"
    else:
        interpretation = "Almost perfect agreement"

    print("Interpretation:", interpretation)

    # --------------------------------------------------------
    # 6. Save results
    # --------------------------------------------------------

    agreement_results = pd.DataFrame({
        "Measure": [
            "Number of Annotators",
            "Annotated Sentences",
            "Unanimous Agreement",
            "Unanimous Agreement (%)",
            "Partial Agreement",
            "Partial Agreement (%)",
            "Fleiss Kappa",
            "Interpretation"
        ],
        "Value": [
            3,
            len(labels),
            unanimous,
            round(unanimous_percentage, 2),
            partial,
            round(partial_percentage, 2),
            round(kappa, 4),
            interpretation
        ]
    })

    display(agreement_results)

    agreement_results.to_csv(
        OUTPUT_DIR + "/three_annotator_agreement.csv",
        index=False,
        encoding="utf-8-sig"
    )

    print("\nResults saved successfully.")

