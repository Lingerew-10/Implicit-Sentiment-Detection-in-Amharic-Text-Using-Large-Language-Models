import torch

print("=" * 60)
print("CONFIGURING TRAINING DATA COLLATOR")
print("=" * 60)

# Verify prerequisites
if "tokenizer" not in globals():
    raise RuntimeError("Tokenizer is missing. Run Cell 24A.")

if "train_tokenized" not in globals():
    raise RuntimeError("Training dataset is missing. Run Cell 24C.")

if "val_tokenized" not in globals():
    raise RuntimeError("Validation dataset is missing. Run Cell 24C.")

# Configure padding
if tokenizer.pad_token_id is None:
    tokenizer.pad_token = tokenizer.eos_token

tokenizer.padding_side = "right"

def sentiment_data_collator(features):

    batch_max_length = max(
        len(feature["input_ids"])
        for feature in features
    )

    batch_max_length = (
        (batch_max_length + 7) // 8
    ) * 8

    input_ids = []
    attention_masks = []
    labels = []

    for feature in features:
        current_length = len(feature["input_ids"])
        padding_length = batch_max_length - current_length

        input_ids.append(
            feature["input_ids"]
            + [tokenizer.pad_token_id] * padding_length
        )

        attention_masks.append(
            feature["attention_mask"]
            + [0] * padding_length
        )

        labels.append(
            feature["labels"]
            + [-100] * padding_length
        )

    return {
        "input_ids": torch.tensor(input_ids, dtype=torch.long),
        "attention_mask": torch.tensor(attention_masks, dtype=torch.long),
        "labels": torch.tensor(labels, dtype=torch.long)
    }

print("Padding token:", tokenizer.pad_token)
