import pandas as pd

LABELS = ["Positive", "Negative", "Neutral"]

SYSTEM_PROMPT = """
You are an expert Amharic sentiment analysis model.
Analyze the implicit sentiment expressed in the Amharic text.
Consider contextual meaning, implied opinions, and emotional intention.
Do not classify based only on individual positive or negative words.
Return exactly one label:
Positive, Negative, or Neutral.
Do not provide explanations.
"""

